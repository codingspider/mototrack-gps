/** Fills {name} places in a text: fillValues('{n} min', { n: 5 }) gives '5 min'. */
export function fillValues(text, values) {
  if (!values) {
    return text;
  }
  return text.replace(/\{(\w+)\}/g, (match, name) => (values[name] === undefined ? match : String(values[name])));
}

/**
 * Translate without React (thunks, parsers, tests). Looks in the keyed words first (translations.js), then in the
 * English-sentence list (phrases.js), then falls back to English, then to the key itself.
 * @param {string} language 'en' | 'bn'
 */
export function translate(language, key, values) {
  const own = translations[language] || translations.en;
  const phrase = language === 'bn' ? bnPhrases[key] : undefined;
  return fillValues(own[key] || phrase || translations.en[key] || key, values);
}

/** English text without the language context, for pure helpers (and their tests). Same shape as t(). */
export function englishText(key, values) {
  return translate('en', key, values);
}

